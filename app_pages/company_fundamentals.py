def _format_cell(value, kind: str) -> str:
    if value is None or pd.isna(value):
        return "—"
    if kind == "eps":
        return f"${value:,.2f}"
    return f"${value / 1e6:,.0f}M"


def _curated_table(statement: dict, rows: list[tuple[str, str]]) -> pd.DataFrame:
    """Rows=curated labels (index), columns=[Trend, then dates ascending]. Trend
    holds each row's own raw (unformatted, same-scale-as-the-rest-of-the-page)
    values as a plain list of floats -- st.dataframe's LineChartColumn renders a
    list cell as an inline sparkline, so this needs the numbers, not the formatted
    "$X,XXXM" strings the date columns use. A missing point becomes 0.0, not None --
    confirmed the chart column silently falls back to showing the raw list as text
    if any entry is None. Placed first (right after the label column) per direct
    user request, so the shape reads before any of the numbers do. Empty when the
    statement has none of these labels at all (e.g. an ETF's empty statement)."""
    all_dates = sorted({d for label, _ in rows for d in (statement.get(label) or {})})
    if not all_dates:
        return pd.DataFrame()
    data = {label: [_format_cell((statement.get(label) or {}).get(d), kind) for d in all_dates] for label, kind in rows}
    df = pd.DataFrame(data, index=all_dates).T
    trend = {
        label: [
            (v / 1e6 if kind == "money" else v) if v is not None and not pd.isna(v) else 0.0
            for v in ((statement.get(label) or {}).get(d) for d in all_dates)
        ]
        for label, kind in rows
    }
    df.insert(0, "Trend", [trend[label] for label in df.index])
    return df


def _raw_table(statement: dict, exclude_labels: set) -> pd.DataFrame:
    """Every OTHER row the statement actually returned, in its native (unformatted)
    units -- deliberately not forced into the curated table's money/EPS formatting,
    since a raw statement mixes dollar amounts, per-share figures, share counts, and
    ratios/rates with no metadata telling this page which is which.

    V4.24 -- gains the same "Trend" sparkline column the curated table above
    already has (same LineChartColumn convention, a missing point becomes 0.0
    not None for the same reason -- the chart column silently falls back to
    showing the raw list as text otherwise). Unlike the curated table, these
    values are NOT rescaled (e.g. ÷1e6) -- each row keeps its own native units,
    since the sparkline here is read as a shape over time per row, not compared
    in magnitude against any other row."""
    remaining = {label: values for label, values in statement.items() if label not in exclude_labels}
    if not remaining:
        return pd.DataFrame()
    all_dates = sorted({d for values in remaining.values() for d in values})
    data = {label: [values.get(d) for d in all_dates] for label, values in remaining.items()}
    df = pd.DataFrame(data, index=all_dates).T
    trend = {
        label: [v if v is not None and not pd.isna(v) else 0.0 for v in (values.get(d) for d in all_dates)]
        for label, values in remaining.items()
    }
    df.insert(0, "Trend", [trend[label] for label in df.index])
    return df


def _render_statement_tab(statement: dict, rows: list[tuple[str, str]], unit_caption: str):
    if not statement:
        st.info("No data available for this statement.")
        return
    st.caption(unit_caption)
    st.dataframe(
        _curated_table(statement, rows), use_container_width=True,
        column_config={"Trend": st.column_config.LineChartColumn("Trend", width="small")},
    )
    with st.expander("What do these line items mean?"):
        for label, _ in rows:
            st.caption(f"**{label}** -- {ROW_HELP.get(label, '')}")
    raw = _raw_table(statement, {label for label, _ in rows})
    if not raw.empty:
        with st.expander(f"View all line items ({len(raw)} more)"):
            st.caption(
                "Values as reported by Yahoo Finance, in their native units (not "
                "reformatted) -- dollar amounts, per-share figures, and share counts "
                "may appear side by side."
            )
            st.dataframe(
                raw, use_container_width=True,
                column_config={"Trend": st.column_config.LineChartColumn("Trend", width="small")},
            )

